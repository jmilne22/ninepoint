CELL_W = 5
CELL_H = 9
BASELINE = 7      # rows 0..6 sit above the baseline
# Glyphs that look better narrow, so text does not read as a picket fence.
NARROW = {"i": 3, "l": 3, "j": 4, ".": 2, ",": 3, ":": 2, ";": 3, "!": 2,
          "'": 2, "|": 2, " ": 3, "(": 3, ")": 3, "-": 4, "t": 4, "f": 4}


def advance(ch):
    """Pixel width of a glyph including one column of letter spacing."""
    return NARROW.get(ch, CELL_W) + 1


def trimmed(ch):
    """The glyph, cropped to its advance width so narrow letters really are."""
    rows = GLYPHS.get(ch)
    if rows is None:
        return None
    w = NARROW.get(ch, CELL_W)
    if w == CELL_W:
        return rows
    # keep the leftmost inked column onwards
    first = CELL_W
    for r in rows:
        for x, c in enumerate(r):
            if c == "#":
                first = min(first, x)
    first = min(first, CELL_W - w)
    return [r[first:first + w].ljust(w) for r in rows]
